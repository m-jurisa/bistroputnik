function localizedMap(callback) {
  return Object.fromEntries(locales.map((locale) => [locale, callback(locale)]));
}

function articleParagraph(config, paragraph, locale) {
  if (paragraph === 'intro') {
    return config.intro?.[locale] || config.intro?.en;
  }

  if (paragraph === 'recommendation') {
    return config.recommendation?.[locale] || config.recommendation?.en;
  }

  return paragraph?.[locale] || paragraph?.en || '';
}

function buildArticleSections(config) {
  const blueprint = articleSectionBlueprints[config.key];

  if (!blueprint) {
    return {};
  }

  return localizedMap((locale) =>
    blueprint.map((section) => ({
      title: section.title[locale] || section.title.en,
      paragraphs: section.paragraphs
        .map((paragraph) => articleParagraph(config, paragraph, locale))
        .filter(Boolean),
    }))
  );
}

function buildOgTitle(title) {
  return localizedMap((locale) => `${title[locale]} | ${ogLabels[locale].ogCta}`);
}

function buildOgDescription(description) {
  return localizedMap((locale) => `${description[locale]} ${ogLabels[locale].ogDescriptionCta}`);
}

